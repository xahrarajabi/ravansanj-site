export function interpretTrait(traitKey: string, score: number, label?: string): string {
  const band = getBandContent(traitKey, score);
  if (band) return `${band.title}. ${band.description}`;
  const name = label || getTraitLabel(traitKey);
  if (score >= 80) return `${name} شما در سطح بالایی است؛ این نقطه قوت را حفظ کنید.`;
  if (score >= 40) return `${name} شما خوب است و با تمرین‌های کوچک قوی‌تر می‌شود.`;
  return `${name} نیاز به توجه دارد؛ از گام‌های کوچک و پایدار شروع کنید.`;
}

