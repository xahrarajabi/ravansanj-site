export function getTraitContent(traitKey: string): TraitContent | null {
  return TRAIT_CONTENT[traitKey] || null;
}

export function getTraitLabel(traitKey: string): string {
  return TRAIT_CONTENT[traitKey]?.label || traitKey;
}

export function getBandContent(traitKey: string, score: number): TraitBandContent | null {
  const content = TRAIT_CONTENT[traitKey];
  if (!content) return null;
  return content.bands[scoreToBand(score)];
}

