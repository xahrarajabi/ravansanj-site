export function scoreToBand(score: number): BandKey {
  if (score >= 80) return "high";
  if (score >= 40) return "mid";
  return "low";
}

export function bandLabel(band: BandKey): string {
  if (band === "high") return "بالا";
  if (band === "mid") return "متوسط";
  return "نیازمند توجه";
}

