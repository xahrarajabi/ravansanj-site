import {
  CHAPTERS,
  ROLE_META,
  TYPE_BY_CODE,
  type ChapterKey,
  type TypeDef,
} from "@/lib/personality/types/catalog";

function p(type: TypeDef, extra: string) {
  return extra.replaceAll("{n}", type.nickname).replaceAll("{c}", type.code);
}

export function chapterParagraphs(code: string, chapter: ChapterKey): string[] {
  const type = TYPE_BY_CODE[code];
  if (!type) return ["تیپ یافت نشد."];
  const role = ROLE_META[type.role];
  const e = code[0] === "E";
  const n = code[1] === "N";
  const t = code[2] === "T";
  const j = code[3] === "J";

  const energy = e
    ? "انرژی‌ات بیشتر در تعامل و بیان زنده شکوفا می‌شود"
    : "انرژی‌ات با خلوت، عمق و زمان بی‌وقفه بازمی‌گردد";
  const mind = n
    ? "ذهنت به الگو، معنا و امکان‌های هنوز ندیده متمایل است"
    : "ذهنت به واقعیت ملموس، تجربه و جزئیات قابل‌اتکا متمایل است";
  const nature = t
    ? "در تصمیم، منطق و پیامد را زودتر از حال جمع وزن می‌کنی"
    : "در تصمیم، حال افراد و ارزش‌های انسانی وزن سنگینی دارند";
  const tactics = j
    ? "ساختار، مهلت و بستن پرونده به تو حس کنترل می‌دهد"
    : "انعطاف، بداهه و باز ماندن گزینه‌ها برایت طبیعی‌تر است";

  switch (chapter) {
    case "intro":
      return [
        p(type, `{n} (${type.code}) در خانوادهٔ «${role.title}» جای می‌گیرد. ${type.hook}`),
        `${energy}. ${mind}. ${nature}. ${tactics}. این ترکیب یک برچسب پزشکی نیست؛ نقشهٔ ترجیح است برای کار، رابطه و رشد.`,
        `شخصیت این تیپ را جایگزین تشخیص یا درمان نمی‌داند. هدف، زبان مشترک برای دیدن الگوهایت است تا انتخاب‌های روزمره آگاهانه‌تر شود.`,
      ];
    case "strengths":
      return [
        p(type, `نقطهٔ قوت {n} معمولاً جایی است که ${mind.split("،")[0]} با ${nature.split("،")[0]} هم‌مسیر می‌شود.`),
        e
          ? "وقتی فضا برای گفتگو و آزمایش زنده باشد، سریع ایده می‌سازی و جمع را حرکت می‌دهی. خطر این است که عمق را فدای سرعت کنی."
          : "وقتی فضا برای فکر عمیق باشد، کیفیت کار بالا می‌رود. خطر این است که بیش از حد در ذهن بمانی و بازخورد دیر برسد.",
        j
          ? "تعهد به اتمام کار، سرمایهٔ توست. رشد این است که جایی برای اصلاح میان‌راه هم باقی بگذاری."
          : "انطباق سریع، سرمایهٔ توست. رشد این است که بعضی تصمیم‌ها را ببندی تا انرژی پخش نشود.",
        t
          ? "صراحت منطقی‌ات مفید است اگر با یک جملهٔ انسانی شروع شود؛ وگرنه ممکن است سرد شنیده شوی."
          : "مراقبتت از حال جمع ارزشمند است اگر مرز خودت را هم نگه داری؛ وگرنه خستگی پنهان جمع می‌شود.",
      ];
    case "relationships":
      return [
        p(type, `در رابطه نزدیک، {n} معمولاً ${nature}. شریک زندگی اگر این وزن را بفهمد، تعارض کمتر شخصی می‌شود.`),
        e
          ? "نیاز به گفتگو و تجربه مشترک داری؛ سکوت طولانی را گاهی دوری می‌خوانی. قرارداد کوچک برای زمان باهم و زمان جدا کمک می‌کند."
          : "نیاز به بازیابی تنهایی داری؛ شلوغی مداوم را فشار می‌بینی. گفتن این نیاز قبل از خستگی، سوءتفاهم را کم می‌کند.",
        "ابزار ساده: یک موضوع را در میان بگذار، یک احساس را نام ببر، یک درخواست مشخص بگو. {n} وقتی این سه را جدا کند، رابطه امن‌تر می‌شود.".replace(
          "{n}",
          type.nickname
        ),
      ];
    case "friends":
      return [
        p(type, `دوستی برای {n} وقتی زنده است که ${n ? "ایده و معنا" : "تجربه مشترک و قابل‌اتکا"} در آن جریان داشته باشد.`),
        e
          ? "حلقهٔ دوستانت ممکن است وسیع باشد؛ کیفیت را با چند رابطهٔ عمیق‌تر متعادل کن."
          : "حلقهٔ کوچک و پایدار برایت طبیعی است؛ گاهی دعوت فعال لازم است تا رابطه از روی عادت نخوابد.",
        "وفاداری‌ات وقتی می‌درخشد که وقت و توجه را قابل‌پیش‌بینی کنی، نه فقط در بحران حاضر شوی.",
      ];
    case "parents":
      return [
        p(type, `در نقش والد یا فرزند بزرگ، {n} الگوی ${j ? "ساختار و مسئولیت" : "آزادی و کشف"} را به خانه می‌آورد.`),
        t
          ? "توضیح منطقی به کودک کمک می‌کند اگر با گرمای حضور همراه باشد. قانون بدون رابطه، مقاومت می‌سازد."
          : "همدلی‌ات پناه می‌سازد اگر مرز و پیامد هم روشن باشد. مهربانی بدون چارچوب، اضطراب پنهان می‌آورد.",
        "یک آیین کوتاه روزانه — غذا، پیاده‌روی، یا مرور روز — از ده‌ها نصیحت مؤثرتر است.",
      ];
    case "careers":
      return [
        p(type, `مسیر شغلی مناسب {n} جایی است که ${mind} و ${tactics}.`),
        type.role === "analysts"
          ? "محیط‌های مسئله‌محور، پژوهش، محصول، استراتژی یا آموزش مفهومی معمولاً انرژی می‌دهند. کارهای صرفاً تکراری بدون فضای فکر، فرسوده می‌کنند."
          : type.role === "diplomats"
            ? "نقش‌هایی با معنا، مربیگری، محتوا، مشاوره یا ساخت جامعه معمولاً می‌نشینند. محیط بی‌روح و صرفاً عددی، انگیزه را می‌خشکاند."
            : type.role === "sentinels"
              ? "نقش‌هایی با مسئولیت روشن، عملیات، آموزش کاربردی یا خدمت پایدار معمولاً رضایت می‌سازند. هرج‌ومرج بدون نقش، انرژی می‌گیرد."
              : "نقش‌هایی با مهارت عملی، میدان، فروش حضوری یا خلق تجربه معمولاً زنده می‌مانند. میز بی‌تحرک طولانی، حوصله را می‌برد.",
        "قبل از تغییر شغل بزرگ، دو هفته کار فعلی را با سه معیار بسنج: انرژی روزانه، یادگیری، و اثر قابل‌دیدن. {n} وقتی این سه هم‌جهت شوند پایدارتر می‌ماند.".replace(
          "{n}",
          type.nickname
        ),
      ];
    case "workplace":
      return [
        p(type, `در تیم، {n} معمولاً ${e ? "ایده‌ها را زود روی میز می‌گذارد" : "قبل از جلسه در سکوت کیفیت می‌سازد"}.`),
        j
          ? "از دستور کار و مالکیت مشخص استقبال می‌کنی. جلسه بدون خروجی مکتوب برایت اتلاف است."
          : "از فضای آزمایش و تغییر مسیر استقبال می‌کنی. بوروکراسی سنگین انگیزه‌ات را کم می‌کند.",
        "بازخورد مفید برای تو: مشخص، با مثال، و با یک گام بعدی. تعریف کلی یا نقد مبهم کمتر به کارت می‌آید.",
      ];
    case "conclusion":
      return [
        p(type, `{n} بودن یعنی ${type.hook} این توصیف سقف تو نیست؛ نقطهٔ شروع تمرین است.`),
        "سه حرکت پیشنهادی: یک نقطهٔ قوت را این هفته عمداً به کار ببر؛ یک نقطهٔ رشد را با تمرین ده‌دقیقه‌ای لمس کن؛ از یک نفر نزدیک بپرس کدام رفتار تو را بیشتر می‌بیند.",
        "اگر گزارش عمیق‌تر شغلی یا رابطه‌ای می‌خواهی، بسته‌های شخصیت آن لایه‌ها را باز می‌کنند — بدون ادعای درمان.",
      ];
  }
}

export function typeChapterNav(code: string) {
  return CHAPTERS.map((c) => ({
    ...c,
    href: c.slug ? `/types/${code.toLowerCase()}/${c.slug}` : `/types/${code.toLowerCase()}`,
  }));
}

export function allTypeCodes() {
  return Object.keys(TYPE_BY_CODE);
}
